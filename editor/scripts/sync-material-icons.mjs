/**
 * sync-material-icons.mjs — vendors the Material Icon Theme icon set and
 * generates the lookup maps we resolve against.
 *
 * Run manually (`bun run sync:icons`) when bumping the upstream version. The
 * output is committed, so neither `bun run build` nor `tauri build` depends on
 * this script or on `material-icon-theme` being installed.
 *
 * Why vendor rather than hand-maintain: the previous hand-written maps carried
 * 84 extensions against upstream's 1378, and resolved on the *last* dot
 * segment, so every compound suffix VS Code understands (`service.ts`,
 * `spec.ts`, `stories.tsx`, `d.ts`, ...) silently fell through to the bare
 * extension. Generating from the same manifest VS Code consumes is the only
 * way that stays true as upstream adds icons.
 */

import { createRequire } from 'node:module';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const require = createRequire(import.meta.url);
const repoRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');

const manifestPath = require.resolve('material-icon-theme/dist/material-icons.json');
const pkgPath = require.resolve('material-icon-theme/package.json');
const manifestDir = path.dirname(manifestPath);

const manifest = JSON.parse(fs.readFileSync(manifestPath, 'utf8'));
const { version } = JSON.parse(fs.readFileSync(pkgPath, 'utf8'));

const outIconDir = path.join(repoRoot, 'public/icons/material');
const outMapFile = path.join(repoRoot, 'src/utils/material-icon-map.generated.ts');
// Superseded by public/icons/material — removed so nothing can keep resolving
// against a stale 42-icon set.
const legacyIconDirs = [
  path.join(repoRoot, 'public/icons/files'),
  path.join(repoRoot, 'public/icons/folders'),
];

/**
 * Icon id → bare SVG filename.
 *
 * Upstream indirects some ids through generated `.clone.svg` files (e.g.
 * `angular-service` → `angular-service.clone.svg`), so the id is not usable as
 * a filename and this table cannot be skipped.
 */
function buildIconPaths() {
  const iconPaths = {};
  const missing = [];

  for (const [id, def] of Object.entries(manifest.iconDefinitions)) {
    const abs = path.resolve(manifestDir, def.iconPath);
    if (!fs.existsSync(abs)) {
      missing.push(`${id} → ${def.iconPath}`);
      continue;
    }
    iconPaths[id] = path.basename(abs);
  }

  // Fail loudly: an upstream restructure that silently dropped icons would
  // otherwise ship as broken <img> tags across the whole explorer.
  if (missing.length > 0) {
    throw new Error(
      `${missing.length} iconDefinitions point at missing files:\n  ${missing.slice(0, 10).join('\n  ')}`,
    );
  }

  return iconPaths;
}

function copyIcons(iconPaths) {
  fs.rmSync(outIconDir, { recursive: true, force: true });
  fs.mkdirSync(outIconDir, { recursive: true });

  for (const file of new Set(Object.values(iconPaths))) {
    fs.copyFileSync(path.join(manifestDir, '..', 'icons', file), path.join(outIconDir, file));
  }
}

/** Lowercases keys so lookups can normalise once at the call site. */
function lowerKeys(obj) {
  const out = {};
  for (const [k, v] of Object.entries(obj ?? {})) out[k.toLowerCase()] = v;
  return out;
}

function serialize(name, obj) {
  return `export const ${name}: Record<string, string> = ${JSON.stringify(obj, null, 0)};\n`;
}

function buildModule(iconPaths) {
  const parts = [
    '// GENERATED BY scripts/sync-material-icons.mjs — DO NOT EDIT BY HAND.',
    `// Source: material-icon-theme@${version} (MIT, Philipp Kief).`,
    '// Regenerate with: bun run sync:icons',
    '',
    `export const MATERIAL_ICON_THEME_VERSION = '${version}';`,
    '',
    '/** Icon id → SVG filename under /icons/material/. */',
    serialize('ICON_PATHS', iconPaths),
    serialize('FILE_NAMES', lowerKeys(manifest.fileNames)),
    serialize('FILE_EXTENSIONS', lowerKeys(manifest.fileExtensions)),
    serialize('FOLDER_NAMES', lowerKeys(manifest.folderNames)),
    serialize('FOLDER_NAMES_EXPANDED', lowerKeys(manifest.folderNamesExpanded)),
    '',
    '// Light-theme overrides — upstream ships dedicated variants for icons that',
    '// wash out on light backgrounds. Consulted before the base maps above when',
    '// the active theme is light.',
    serialize('LIGHT_FILE_NAMES', lowerKeys(manifest.light?.fileNames)),
    serialize('LIGHT_FILE_EXTENSIONS', lowerKeys(manifest.light?.fileExtensions)),
    serialize('LIGHT_FOLDER_NAMES', lowerKeys(manifest.light?.folderNames)),
    serialize('LIGHT_FOLDER_NAMES_EXPANDED', lowerKeys(manifest.light?.folderNamesExpanded)),
    '',
    `export const DEFAULT_FILE = '${manifest.file}';`,
    `export const DEFAULT_FOLDER = '${manifest.folder}';`,
    `export const DEFAULT_FOLDER_OPEN = '${manifest.folderExpanded}';`,
    '',
  ];
  return parts.join('\n');
}

const iconPaths = buildIconPaths();
copyIcons(iconPaths);
fs.writeFileSync(outMapFile, buildModule(iconPaths));

for (const dir of legacyIconDirs) {
  fs.rmSync(dir, { recursive: true, force: true });
}

const count = new Set(Object.values(iconPaths)).size;
console.log(`material-icon-theme@${version}`);
console.log(`  ${count} icons → public/icons/material/`);
console.log(`  ${Object.keys(manifest.fileNames).length} fileNames, ` +
  `${Object.keys(manifest.fileExtensions).length} fileExtensions, ` +
  `${Object.keys(manifest.folderNames).length} folderNames`);
console.log(`  map → src/utils/material-icon-map.generated.ts`);
